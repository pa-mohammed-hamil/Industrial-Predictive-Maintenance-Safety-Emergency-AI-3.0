async def get_request_id(
    request: Request,
) -> str | None:
    """
    Retrieve request ID generated by middleware.

    Falls back to the incoming X-Request-ID header.
    """

    request_id = getattr(
        request.state,
        "request_id",
        None,
    )

    if request_id:
        return request_id

    return request.headers.get(
        "X-Request-ID"
    )


RequestIdDep = Annotated[
    str | None,
    Depends(get_request_id),
]


async def get_client_ip(
    request: Request,
) -> str | None:
    """
    Return the client IP.

    Trust forwarded headers only when the deployment/proxy
    configuration explicitly permits them.
    """

    settings = get_settings()

    if settings.trust_proxy_headers:
        forwarded_for = request.headers.get(
            "X-Forwarded-For"
        )

        if forwarded_for:
            return forwarded_for.split(",")[0].strip()

    if request.client:
        return request.client.host

    return None


ClientIPDep = Annotated[
    str | None,
    Depends(get_client_ip),
]


