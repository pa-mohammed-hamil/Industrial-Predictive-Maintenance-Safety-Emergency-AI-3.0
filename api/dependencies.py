async def get_current_company(
    current_user: CurrentUser,
    db: DBSession,
) -> Company:
    """
    Resolve the user's company/tenant.

    Every tenant-scoped repository/service should receive this
    context rather than trusting a company_id supplied by clients.
    """

    company_id = getattr(
        current_user,
        "company_id",
        None,
    )

    if company_id is None:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="User has no company context",
        )

    result = await db.execute(
        select(Company).where(
            Company.id == company_id,
        )
    )

    company = result.scalar_one_or_none()

    if company is None:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Company not found",
        )

    if hasattr(company, "is_active"):
        if not company.is_active:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Company is inactive",
            )

    return company


CurrentCompany = Annotated[
    Company,
    Depends(get_current_company),
]


