def require_roles(
    *allowed_roles: str,
):
    """
    Create a dependency requiring one of the supplied roles.

    Example:

        current_user: User = Depends(
            require_roles("admin", "engineer")
        )
    """

    async def dependency(
        current_user: CurrentUser,
    ) -> User:

        user_role = getattr(
            current_user,
            "role",
            None,
        )

        role_value = getattr(
            user_role,
            "value",
            user_role,
        )

        if role_value not in allowed_roles:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Insufficient permissions",
            )

        return current_user

    return dependency


def require_active_user(
    current_user: CurrentUser,
) -> User:
    """Explicit active-user dependency."""

    if not current_user.is_active:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="User account is inactive",
        )

    return current_user


ActiveUser = Annotated[
    User,
    Depends(require_active_user),
]


