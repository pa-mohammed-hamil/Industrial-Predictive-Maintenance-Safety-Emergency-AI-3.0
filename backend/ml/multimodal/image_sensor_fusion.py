@dataclass(slots=True, frozen=True)
class BoundingBox:
    x1: float
    y1: float
    x2: float
    y2: float

    def __post_init__(self) -> None:
        if self.x2 < self.x1:
            raise ValueError("x2 must be >= x1")

        if self.y2 < self.y1:
            raise ValueError("y2 must be >= y1")

    @property
    def area(self) -> float:
        return max(
            0.0,
            self.x2 - self.x1,
        ) * max(
            0.0,
            self.y2 - self.y1,
        )


