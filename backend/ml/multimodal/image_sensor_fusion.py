@dataclass(slots=True)
class ImageSensorFusionPolicy:
    max_time_difference_seconds: float = 30.0

    minimum_visual_confidence: float = 0.50
    minimum_sensor_confidence: float = 0.50

    minimum_match_score: float = 0.50

    corroboration_match_score: float = 0.65

    visual_weight: float = 0.45
    sensor_weight: float = 0.45
    correlation_weight: float = 0.10

    temporal_weight: float = 0.30
    asset_weight: float = 0.25
    zone_weight: float = 0.20
    semantic_weight: float = 0.25

    corroboration_bonus: float = 0.10

    low_threshold: float = 0.25
    medium_threshold: float = 0.45
    high_threshold: float = 0.70
    critical_threshold: float = 0.90

    minimum_independent_sources: int = 2


