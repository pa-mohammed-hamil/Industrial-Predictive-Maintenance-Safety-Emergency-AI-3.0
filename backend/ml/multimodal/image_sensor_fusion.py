@dataclass(slots=True)
class VisualDetection:
    detection_id: str

    timestamp: datetime
    detection_type: VisualDetectionType

    confidence: float

    camera_id: str | None = None
    asset_id: str | None = None
    site_id: str | None = None
    zone_id: str | None = None

    bbox: BoundingBox | None = None

    # Useful for thermal cameras / VLM / CV models.
    temperature_c: float | None = None
    severity_score: float | None = None

    model_name: str | None = None
    model_version: str | None = None

    attributes: dict[str, Any] = field(
        default_factory=dict
    )

    metadata: dict[str, Any] = field(
        default_factory=dict
    )

    def __post_init__(self) -> None:
        self.confidence = _clamp(
            self.confidence
        )

        if self.severity_score is not None:
            self.severity_score = _clamp(
                self.severity_score
            )

        if (
            self.temperature_c is not None
            and not _valid_number(
                self.temperature_c
            )
        ):
            raise ValueError(
                "temperature_c must be finite"
            )


