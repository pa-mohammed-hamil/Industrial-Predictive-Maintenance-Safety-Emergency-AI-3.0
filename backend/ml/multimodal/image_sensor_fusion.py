# ============================================================
# Helpers
# ============================================================


def _average(
    values: Sequence[float],
) -> float:

    if not values:
        return 0.0

    return sum(values) / len(values)


def _valid_number(
    value: Any,
) -> bool:

    try:
        return isfinite(
            float(value)
        )
    except (
        TypeError,
        ValueError,
    ):
        return False


def _clamp(
    value: float,
    minimum: float = 0.0,
    maximum: float = 1.0,
) -> float:

    return max(
        minimum,
        min(
            maximum,
            float(value),
        ),
    )


