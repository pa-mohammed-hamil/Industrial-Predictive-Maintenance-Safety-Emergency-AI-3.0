# ============================================================
# Fusion Engine
# ============================================================


class ImageSensorFusionEngine:
    """
    Correlates visual detections with industrial sensor signals.

    Examples
    --------
    Camera smoke detection
        +
    smoke sensor increase
        +
    temperature increase

    -> strongly corroborated smoke/thermal incident.

    Thermal-camera hotspot
        +
    current anomaly
        +
    electrical anomaly

    -> stronger electrical/thermal evidence.

    Person detected
        +
    proximity sensor violation

    -> stronger worker-proximity evidence.

    This module provides evidence fusion only.

    It MUST NOT directly:
        - stop machinery
        - trip breakers
        - trigger suppression systems
        - evacuate workers

    Safety-critical actions belong to the deterministic
    safety/decision engine.
    """

    _SEVERITY_RANK = {
        FusionSeverity.NORMAL: 0,
        FusionSeverity.LOW: 1,
        FusionSeverity.MEDIUM: 2,
        FusionSeverity.HIGH: 3,
        FusionSeverity.CRITICAL: 4,
    }

    def __init__(
        self,
        policy: ImageSensorFusionPolicy | None = None,
    ) -> None:
        self.policy = (
            policy
            or ImageSensorFusionPolicy()
        )

    # ========================================================
    # Public API
    # ========================================================

    def fuse(
        self,
        visual_detections: Iterable[
            VisualDetection
        ],
        sensor_signals: Iterable[
            SensorSignal
        ],
        *,
        asset_id: str | None = None,
        site_id: str | None = None,
        zone_id: str | None = None,
    ) -> ImageSensorFusionResult:

        visuals = self._prepare_visuals(
            visual_detections,
            asset_id=asset_id,
            site_id=site_id,
            zone_id=zone_id,
        )

        sensors = self._prepare_sensors(
            sensor_signals,
            asset_id=asset_id,
            site_id=site_id,
            zone_id=zone_id,
        )

        matches = self._match(
            visuals,
            sensors,
        )

        correlation = self._correlate(
            visuals,
            sensors,
            matches,
        )

        visual_score = (
            self._visual_score(
                visuals
            )
        )

        sensor_score = (
            self._sensor_score(
                sensors
            )
        )

        correlation_score = (
            self._correlation_score(
                correlation,
                matches,
            )
        )

        fused_score = self._fused_score(
            visual_score=visual_score,
            sensor_score=sensor_score,
            correlation_score=correlation_score,
            correlation=correlation,
        )

        confidence = self._confidence(
            visuals,
            sensors,
            correlation,
        )

        event_type = self._event_type(
            visuals,
            sensors,
        )

        severity = self._severity(
            fused_score,
            event_type,
            visuals,
            sensors,
            correlation,
        )

        state = self._state(
            visuals,
            sensors,
            correlation,
            severity,
        )

        evidence = self._evidence(
            visuals,
            sensors,
            matches,
        )

        timestamp = self._timestamp(
            visuals,
            sensors,
        )

        resolved_asset = (
            asset_id
            or self._most_common(
                [
                    item.asset_id
                    for item in [
                        *visuals,
                        *sensors,
                    ]
                    if item.asset_id
                ]
            )
        )

        resolved_site = (
            site_id
            or self._most_common(
                [
                    item.site_id
                    for item in [
                        *visuals,
                        *sensors,
                    ]
                    if item.site_id
                ]
            )
        )

        resolved_zone = (
            zone_id
            or self._most_common(
                [
                    item.zone_id
                    for item in [
                        *visuals,
                        *sensors,
                    ]
                    if item.zone_id
                ]
            )
        )

        requires_safety_review = (
            severity
            in {
                FusionSeverity.HIGH,
                FusionSeverity.CRITICAL,
            }
            and event_type
            in {
                FusionEventType.FIRE,
                FusionEventType.SMOKE,
                FusionEventType.OVERHEATING,
                FusionEventType.ELECTRICAL,
                FusionEventType.RESTRICTED_ZONE,
                FusionEventType.UNSAFE_PROXIMITY,
            }
        )

        requires_maintenance_review = (
            severity
            in {
                FusionSeverity.MEDIUM,
                FusionSeverity.HIGH,
                FusionSeverity.CRITICAL,
            }
            and event_type
            in {
                FusionEventType.OVERHEATING,
                FusionEventType.ELECTRICAL,
                FusionEventType.LEAK,
                FusionEventType.CORROSION,
                FusionEventType.CRACK,
                FusionEventType.EQUIPMENT_DAMAGE,
                FusionEventType.MACHINE_ANOMALY,
            }
        )

        return ImageSensorFusionResult(
            fusion_id=str(uuid4()),
            timestamp=timestamp,
            event_type=event_type,
            state=state,
            severity=severity,
            fused_score=fused_score,
            confidence=confidence,
            asset_id=resolved_asset,
            site_id=resolved_site,
            zone_id=resolved_zone,
            visual_detections=visuals,
            sensor_signals=sensors,
            matches=matches,
            evidence=evidence,
            correlation=correlation,
            primary_visual_type=(
                self._primary_visual_type(
                    visuals
                )
            ),
            primary_sensor_type=(
                self._primary_sensor_type(
                    sensors
                )
            ),
            requires_investigation=(
                severity
                != FusionSeverity.NORMAL
            ),
            requires_maintenance_review=(
                requires_maintenance_review
            ),
            requires_safety_review=(
                requires_safety_review
            ),
            metadata={
                "visual_score":
                    visual_score,
                "sensor_score":
                    sensor_score,
                "correlation_score":
                    correlation_score,
            },
        )

    # ========================================================
    # Filtering
    # ========================================================

    def _prepare_visuals(
        self,
        detections: Iterable[
            VisualDetection
        ],
        *,
        asset_id: str | None,
        site_id: str | None,
        zone_id: str | None,
    ) -> list[VisualDetection]:

        output: list[
            VisualDetection
        ] = []

        for detection in detections:

            if (
                detection.confidence
                < self.policy
                .minimum_visual_confidence
            ):
                continue

            if (
                asset_id is not None
                and detection.asset_id
                not in {None, asset_id}
            ):
                continue

            if (
                site_id is not None
                and detection.site_id
                not in {None, site_id}
            ):
                continue

            if (
                zone_id is not None
                and detection.zone_id
                not in {None, zone_id}
            ):
                continue

            output.append(detection)

        return output

    def _prepare_sensors(
        self,
        signals: Iterable[
            SensorSignal
        ],
        *,
        asset_id: str | None,
        site_id: str | None,
        zone_id: str | None,
    ) -> list[SensorSignal]:

        output: list[
            SensorSignal
        ] = []

        for signal in signals:

            if (
                signal.confidence
                < self.policy
                .minimum_sensor_confidence
            ):
                continue

            if (
                asset_id is not None
                and signal.asset_id
                not in {None, asset_id}
            ):
                continue

            if (
                site_id is not None
                and signal.site_id
                not in {None, site_id}
            ):
                continue

            if (
                zone_id is not None
                and signal.zone_id
                not in {None, zone_id}
            ):
                continue

            output.append(signal)

        return output

    # ========================================================
    # Matching
    # ========================================================

    def _match(
        self,
        visuals: Sequence[
            VisualDetection
        ],
        sensors: Sequence[
            SensorSignal
        ],
    ) -> list[EvidenceMatch]:

        matches: list[
            EvidenceMatch
        ] = []

        for visual in visuals:
            for sensor in sensors:

                temporal = (
                    self._temporal_score(
                        visual.timestamp,
                        sensor.timestamp,
                    )
                )

                asset = self._identity_score(
                    visual.asset_id,
                    sensor.asset_id,
                )

                zone = self._identity_score(
                    visual.zone_id,
                    sensor.zone_id,
                )

                semantic = (
                    self._semantic_score(
                        visual.detection_type,
                        sensor.signal_type,
                    )
                )

                compatible = (
                    semantic > 0.0
                )

                p = self.policy

                score = (
                    temporal
                    * p.temporal_weight
                    + asset
                    * p.asset_weight
                    + zone
                    * p.zone_weight
                    + semantic
                    * p.semantic_weight
                )

                score = _clamp(score)

                if (
                    score
                    < p.minimum_match_score
                ):
                    continue

                matches.append(
                    EvidenceMatch(
                        visual_id=(
                            visual.detection_id
                        ),
                        sensor_id=(
                            sensor.signal_id
                        ),
                        temporal_score=temporal,
                        asset_score=asset,
                        zone_score=zone,
                        semantic_score=semantic,
                        overall_score=score,
                        compatible=compatible,
                    )
                )

        return sorted(
            matches,
            key=lambda item:
                item.overall_score,
            reverse=True,
        )

    def _temporal_score(
        self,
        first: datetime,
        second: datetime,
    ) -> float:

        difference = abs(
            (
                first - second
            ).total_seconds()
        )

        maximum = (
            self.policy
            .max_time_difference_seconds
        )

        if difference > maximum:
            return 0.0

        # Smooth decay instead of a hard
        # same-second requirement.
        return _clamp(
            exp(
                -difference
                / max(
                    maximum / 3.0,
                    1e-6,
                )
            )
        )

    @staticmethod
    def _identity_score(
        first: str | None,
        second: str | None,
    ) -> float:

        if (
            first is None
            or second is None
        ):
            # Unknown identity is weaker
            # evidence, not disagreement.
            return 0.50

        if first == second:
            return 1.0

        return 0.0

    @staticmethod
    def _semantic_score(
        visual_type: VisualDetectionType,
        sensor_type: SensorSignalType,
    ) -> float:

        compatible = (
            _VISUAL_SENSOR_COMPATIBILITY
            .get(
                visual_type,
                set(),
            )
        )

        if sensor_type in compatible:
            return 1.0

        return 0.0

    # ========================================================
    # Correlation
    # ========================================================

    def _correlate(
        self,
        visuals: Sequence[
            VisualDetection
        ],
        sensors: Sequence[
            SensorSignal
        ],
        matches: Sequence[
            EvidenceMatch
        ],
    ) -> FusionCorrelation:

        good_matches = [
            match
            for match in matches
            if (
                match.compatible
                and match.overall_score
                >= self.policy
                .corroboration_match_score
            )
        ]

        temporal = _average(
            [
                item.temporal_score
                for item in good_matches
            ]
        )

        spatial = _average(
            [
                (
                    item.asset_score
                    + item.zone_score
                ) / 2.0
                for item in good_matches
            ]
        )

        semantic = _average(
            [
                item.semantic_score
                for item in good_matches
            ]
        )

        camera_ids = {
            item.camera_id
            for item in visuals
            if item.camera_id
        }

        sensor_ids = {
            item.sensor_id
            for item in sensors
            if item.sensor_id
        }

        independent_sources = (
            len(camera_ids)
            + len(sensor_ids)
        )

        corroborated = (
            bool(good_matches)
            and independent_sources
            >= self.policy
            .minimum_independent_sources
        )

        # Conflicting means we have evidence from both
        # modalities but no semantically meaningful match.
        conflicting = (
            bool(visuals)
            and bool(sensors)
            and not good_matches
        )

        return FusionCorrelation(
            visual_count=len(visuals),
            sensor_count=len(sensors),
            camera_count=len(camera_ids),
            physical_sensor_count=len(
                sensor_ids
            ),
            independent_source_count=(
                independent_sources
            ),
            matched_pairs=len(
                good_matches
            ),
            temporal_agreement=temporal,
            spatial_agreement=spatial,
            semantic_agreement=semantic,
            corroborated=corroborated,
            conflicting=conflicting,
        )

    # ========================================================
    # Scores
    # ========================================================

    @staticmethod
    def _visual_score(
        visuals: Sequence[
            VisualDetection
        ],
    ) -> float:

        if not visuals:
            return 0.0

        scores: list[float] = []

        for detection in visuals:

            severity = (
                detection.severity_score
                if (
                    detection.severity_score
                    is not None
                )
                else detection.confidence
            )

            scores.append(
                _clamp(
                    severity
                    * detection.confidence
                )
            )

        strongest = max(scores)

        corroboration = min(
            0.10,
            max(
                0,
                len(scores) - 1,
            ) * 0.025,
        )

        return _clamp(
            strongest + corroboration
        )

    @staticmethod
    def _sensor_score(
        sensors: Sequence[
            SensorSignal
        ],
    ) -> float:

        if not sensors:
            return 0.0

        scores = [
            _clamp(
                signal.anomaly_score
                * signal.confidence
            )
            for signal in sensors
        ]

        strongest = max(scores)

        corroboration = min(
            0.10,
            max(
                0,
                len(scores) - 1,
            ) * 0.025,
        )

        return _clamp(
            strongest + corroboration
        )

    @staticmethod
    def _correlation_score(
        correlation: FusionCorrelation,
        matches: Sequence[
            EvidenceMatch
        ],
    ) -> float:

        if not matches:
            return 0.0

        strongest_match = max(
            match.overall_score
            for match in matches
        )

        agreement = (
            correlation.temporal_agreement
            + correlation.spatial_agreement
            + correlation.semantic_agreement
        ) / 3.0

        return _clamp(
            strongest_match * 0.60
            + agreement * 0.40
        )

    def _fused_score(
        self,
        *,
        visual_score: float,
        sensor_score: float,
        correlation_score: float,
        correlation: FusionCorrelation,
    ) -> float:

        p = self.policy

        available_weight = 0.0
        score = 0.0

        if visual_score > 0:
            score += (
                visual_score
                * p.visual_weight
            )

            available_weight += (
                p.visual_weight
            )

        if sensor_score > 0:
            score += (
                sensor_score
                * p.sensor_weight
            )

            available_weight += (
                p.sensor_weight
            )

        if correlation_score > 0:
            score += (
                correlation_score
                * p.correlation_weight
            )

            available_weight += (
                p.correlation_weight
            )

        if available_weight <= 0:
            return 0.0

        score /= available_weight

        if correlation.corroborated:
            score += (
                p.corroboration_bonus
            )

        return _clamp(score)

    # ========================================================
    # Confidence
    # ========================================================

    @staticmethod
    def _confidence(
        visuals: Sequence[
            VisualDetection
        ],
        sensors: Sequence[
            SensorSignal
        ],
        correlation: FusionCorrelation,
    ) -> float:

        confidences = [
            item.confidence
            for item in visuals
        ] + [
            item.confidence
            for item in sensors
        ]

        if not confidences:
            return 0.0

        base = _average(
            confidences
        )

        independent_bonus = min(
            0.10,
            max(
                0,
                correlation
                .independent_source_count
                - 1,
            ) * 0.025,
        )

        corroboration_bonus = (
            0.10
            if correlation.corroborated
            else 0.0
        )

        conflict_penalty = (
            0.15
            if correlation.conflicting
            else 0.0
        )

        return _clamp(
            base
            + independent_bonus
            + corroboration_bonus
            - conflict_penalty
        )

    # ========================================================
    # Event classification
    # ========================================================

    def _event_type(
        self,
        visuals: Sequence[
            VisualDetection
        ],
        sensors: Sequence[
            SensorSignal
        ],
    ) -> FusionEventType:

        visual_types = {
            item.detection_type
            for item in visuals
        }

        sensor_types = {
            item.signal_type
            for item in sensors
        }

        if (
            VisualDetectionType.FIRE
            in visual_types
        ):
            return FusionEventType.FIRE

        if (
            VisualDetectionType.SMOKE
            in visual_types
            or SensorSignalType.SMOKE
            in sensor_types
        ):
            return FusionEventType.SMOKE

        if (
            VisualDetectionType.HOTSPOT
            in visual_types
            or SensorSignalType.TEMPERATURE
            in sensor_types
        ):
            return (
                FusionEventType.OVERHEATING
            )

        if (
            visual_types
            & {
                VisualDetectionType.SPARK,
                VisualDetectionType.ARC,
            }
            or sensor_types
            & {
                SensorSignalType.CURRENT,
                SensorSignalType.VOLTAGE,
                SensorSignalType.POWER,
            }
        ):
            return FusionEventType.ELECTRICAL

        if (
            VisualDetectionType.LIQUID_LEAK
            in visual_types
        ):
            return FusionEventType.LEAK

        if (
            VisualDetectionType.CORROSION
            in visual_types
        ):
            return FusionEventType.CORROSION

        if (
            VisualDetectionType.CRACK
            in visual_types
        ):
            return FusionEventType.CRACK

        if (
            VisualDetectionType.DAMAGE
            in visual_types
        ):
            return (
                FusionEventType
                .EQUIPMENT_DAMAGE
            )

        if (
            VisualDetectionType.PERSON
            in visual_types
            and SensorSignalType.PROXIMITY
            in sensor_types
        ):
            return (
                FusionEventType
                .UNSAFE_PROXIMITY
            )

        if (
            VisualDetectionType.MOTION
            in visual_types
            or SensorSignalType.MOTION
            in sensor_types
        ):
            return (
                FusionEventType
                .ABNORMAL_MOTION
            )

        if (
            sensor_types
            & {
                SensorSignalType.VIBRATION,
                SensorSignalType.ACOUSTIC,
            }
        ):
            return (
                FusionEventType
                .MACHINE_ANOMALY
            )

        return FusionEventType.UNKNOWN

    # ========================================================
    # Severity
    # ========================================================

    def _severity(
        self,
        score: float,
        event_type: FusionEventType,
        visuals: Sequence[
            VisualDetection
        ],
        sensors: Sequence[
            SensorSignal
        ],
        correlation: FusionCorrelation,
    ) -> FusionSeverity:

        # Hard evidence can raise review severity,
        # but this still does not authorize actions.
        visual_fire = any(
            item.detection_type
            == VisualDetectionType.FIRE
            and item.confidence >= 0.90
            for item in visuals
        )

        severe_sensor = any(
            item.anomaly_score >= 0.95
            and item.confidence >= 0.80
            for item in sensors
        )

        if (
            event_type
            == FusionEventType.FIRE
            and visual_fire
            and correlation.corroborated
        ):
            return FusionSeverity.CRITICAL

        if (
            score
            >= self.policy
            .critical_threshold
        ):
            return FusionSeverity.CRITICAL

        if (
            severe_sensor
            and correlation.corroborated
        ):
            return FusionSeverity.CRITICAL

        if (
            score
            >= self.policy.high_threshold
        ):
            return FusionSeverity.HIGH

        if (
            score
            >= self.policy.medium_threshold
        ):
            return FusionSeverity.MEDIUM

        if (
            score
            >= self.policy.low_threshold
        ):
            return FusionSeverity.LOW

        return FusionSeverity.NORMAL

    # ========================================================
    # State
    # ========================================================

    @staticmethod
    def _state(
        visuals: Sequence[
            VisualDetection
        ],
        sensors: Sequence[
            SensorSignal
        ],
        correlation: FusionCorrelation,
        severity: FusionSeverity,
    ) -> FusionState:

        if (
            severity
            == FusionSeverity.CRITICAL
        ):
            return FusionState.CRITICAL

        if correlation.corroborated:
            return FusionState.CORROBORATED

        if correlation.conflicting:
            return FusionState.CONFLICTING

        if visuals and not sensors:
            return FusionState.VISUAL_ONLY

        if sensors and not visuals:
            return FusionState.SENSOR_ONLY

        return FusionState.UNCONFIRMED

    # ========================================================
    # Evidence
    # ========================================================

    @staticmethod
    def _evidence(
        visuals: Sequence[
            VisualDetection
        ],
        sensors: Sequence[
            SensorSignal
        ],
        matches: Sequence[
            EvidenceMatch
        ],
    ) -> list[FusionEvidence]:

        evidence: list[
            FusionEvidence
        ] = []

        for visual in visuals:
            evidence.append(
                FusionEvidence(
                    source=(
                        EvidenceSource
                        .THERMAL_CAMERA
                        if visual.detection_type
                        == VisualDetectionType.HOTSPOT
                        else EvidenceSource.CAMERA
                    ),
                    source_id=(
                        visual.detection_id
                    ),
                    evidence_type=(
                        visual
                        .detection_type
                        .value
                    ),
                    score=(
                        visual.severity_score
                        if (
                            visual
                            .severity_score
                            is not None
                        )
                        else visual.confidence
                    ),
                    confidence=(
                        visual.confidence
                    ),
                    timestamp=(
                        visual.timestamp
                    ),
                    description=(
                        "Visual model detected "
                        f"{visual.detection_type.value}"
                    ),
                    asset_id=(
                        visual.asset_id
                    ),
                    zone_id=(
                        visual.zone_id
                    ),
                    metadata={
                        "camera_id":
                            visual.camera_id,
                        "model_name":
                            visual.model_name,
                        "model_version":
                            visual.model_version,
                    },
                )
            )

        for sensor in sensors:
            evidence.append(
                FusionEvidence(
                    source=(
                        EvidenceSource.SENSOR
                    ),
                    source_id=(
                        sensor.signal_id
                    ),
                    evidence_type=(
                        sensor.signal_type.value
                    ),
                    score=(
                        sensor.anomaly_score
                    ),
                    confidence=(
                        sensor.confidence
                    ),
                    timestamp=(
                        sensor.timestamp
                    ),
                    description=(
                        f"{sensor.signal_type.value} "
                        "sensor supplied abnormal "
                        "physical evidence"
                    ),
                    asset_id=(
                        sensor.asset_id
                    ),
                    zone_id=(
                        sensor.zone_id
                    ),
                    metadata={
                        "sensor_id":
                            sensor.sensor_id,
                        "value":
                            sensor.value,
                        "unit":
                            sensor.unit,
                    },
                )
            )

        for match in matches:
            evidence.append(
                FusionEvidence(
                    source=(
                        EvidenceSource
                        .MULTIMODAL
                    ),
                    source_id=(
                        f"{match.visual_id}:"
                        f"{match.sensor_id}"
                    ),
                    evidence_type=(
                        "visual_sensor_match"
                    ),
                    score=(
                        match.overall_score
                    ),
                    confidence=(
                        match.overall_score
                    ),
                    timestamp=(
                        datetime.now(
                            timezone.utc
                        )
                    ),
                    description=(
                        "Visual and physical "
                        "sensor evidence correlated"
                    ),
                    metadata={
                        "temporal_score":
                            match.temporal_score,
                        "asset_score":
                            match.asset_score,
                        "zone_score":
                            match.zone_score,
                        "semantic_score":
                            match.semantic_score,
                    },
                )
            )

        return evidence

    # ========================================================
    # Primary sources
    # ========================================================

    @staticmethod
    def _primary_visual_type(
        visuals: Sequence[
            VisualDetection
        ],
    ) -> VisualDetectionType | None:

        if not visuals:
            return None

        strongest = max(
            visuals,
            key=lambda item:
                item.confidence
                * (
                    item.severity_score
                    if (
                        item.severity_score
                        is not None
                    )
                    else 1.0
                ),
        )

        return strongest.detection_type

    @staticmethod
    def _primary_sensor_type(
        sensors: Sequence[
            SensorSignal
        ],
    ) -> SensorSignalType | None:

        if not sensors:
            return None

        strongest = max(
            sensors,
            key=lambda item:
                item.anomaly_score
                * item.confidence,
        )

        return strongest.signal_type

    # ========================================================
    # Utilities
    # ========================================================

    @staticmethod
    def _timestamp(
        visuals: Sequence[
            VisualDetection
        ],
        sensors: Sequence[
            SensorSignal
        ],
    ) -> datetime:

        timestamps = [
            item.timestamp
            for item in visuals
        ] + [
            item.timestamp
            for item in sensors
        ]

        if not timestamps:
            return datetime.now(
                timezone.utc
            )

        return max(timestamps)

    @staticmethod
    def _most_common(
        values: Sequence[str],
    ) -> str | None:

        if not values:
            return None

        counts: dict[str, int] = {}

        for value in values:
            counts[value] = (
                counts.get(value, 0)
                + 1
            )

        return max(
            counts,
            key=counts.get,  # type: ignore[arg-type]
        )


